import time
import random
import matplotlib.pyplot as plt

# 1. Implement: Insertion Sort algorithm counting comparisons and shifts
def insertion_sort(arr):
    comparisons = 0
    shifts = 0
    a = list(arr)
    for i in range(1, len(a)):
        key = a[i]
        j = i - 1
        while j >= 0:
            comparisons += 1
            if a[j] > key:
                a[j + 1] = a[j]
                shifts += 1
                j -= 1
            else:
                break
        if j >= 0:
            comparisons += 1
        a[j + 1] = key
    return comparisons, shifts

# 2. Experiment & 3. Analyze: Time it for n = 100 to 5,000 on sorted, reverse-sorted, and random inputs
def run_insertion_analysis():
    sizes = [100, 500, 1000, 2500, 5000]
    data_types = {
        "Sorted": lambda n: list(range(n)),
        "Reverse-Sorted": lambda n: list(range(n, 0, -1)),
        "Random": lambda n: [random.randint(0, 10000) for _ in range(n)]
    }
    
    results = {dt: [] for dt in data_types}
    
    for dt_name, generator in data_types.items():
        print(f"\n--- Testing Data Type: {dt_name} ---")
        times = []
        for n in sizes:
            arr = generator(n)
            
            # Measure running time
            start_time = time.perf_counter()
            insertion_sort(arr)
            end_time = time.perf_counter()
            
            elapsed = end_time - start_time
            times.append(elapsed)
            print(f"n = {n} | Time: {elapsed:.6f} seconds")
            
        results[dt_name] = times

    # 4. Report: Plot running time against n
    plt.figure(figsize=(10, 5))
    for dt_name, times in results.items():
        plt.plot(sizes, times, marker='o', label=dt_name)
        
    plt.title("Empirical Analysis of Insertion Sort")
    plt.xlabel("Input Size (n)")
    plt.ylabel("Running Time (seconds)")
    plt.legend()
    plt.grid(True)
    plt.tight_layout()
    plt.show()

if __name__ == "__main__":
    run_insertion_analysis()